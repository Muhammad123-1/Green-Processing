import { NextRequest, NextResponse } from 'next/server'
import { prisma } from '@/lib/prisma'
import { getSession } from '@/app/actions/auth'
import { isDateStr, sanitizeDayReport, hasReportData, getDayReport, autoBuildDayReport } from '@/lib/shopReport'

export const dynamic = 'force-dynamic'

/**
 * Fetch daily workshop report for a specific date.
 * Returns saved report (if any), auto-calculated report from arrivals & expenses,
 * and previous day ending balances.
 * If date is past 23:00 or a past day, and no report was manually saved,
 * it auto-archives the day's report (or flags as unfilled).
 */
export async function GET(req: NextRequest) {
  try {
    const { searchParams } = new URL(req.url)
    const date = searchParams.get('date')
    if (!date || !isDateStr(date)) {
      return NextResponse.json({ error: "Sana ko'rsatilmadi" }, { status: 400 })
    }

    const [existingExpense, dayArrivals, earlierExpenses] = await Promise.all([
      prisma.shopExpense.findUnique({ where: { date } }),
      prisma.shopArrival.findMany({ where: { date }, orderBy: { id: 'asc' } }),
      prisma.shopExpense.findMany({
        where: { date: { lt: date } },
        orderBy: { date: 'desc' },
        take: 15,
      })
    ])

    // Find closest earlier report with end balances
    let prevEnd: Record<string, number> | null = null
    for (const e of earlierExpenses) {
      const rep = getDayReport(e)
      const end = rep?.balances?.end
      if (end && Object.keys(end).length > 0) {
        prevEnd = end
        break
      }
    }

    const saved = getDayReport(existingExpense)
    const auto = autoBuildDayReport(date, dayArrivals, existingExpense, prevEnd)

    // Check if auto-archive should trigger:
    // Past day or after 23:00 tonight (Uzbekistan timezone UTC+5)
    const autoArchive = searchParams.get('autoArchive') === 'true'
    const nowUz = new Date(Date.now() + 5 * 3600 * 1000)
    const todayUz = nowUz.toISOString().slice(0, 10)
    const currentHourUz = nowUz.getUTCHours()
    const isPastOrLate = date < todayUz || (date === todayUz && currentHourUz >= 23)

    let finalSaved = saved
    if (!saved && (autoArchive || isPastOrLate)) {
      const now = new Date().toISOString()
      const prevBalances = ((existingExpense?.balances as any) || {}) as Record<string, any>
      const balances: Record<string, any> = { ...prevBalances }

      if (auto.hasData) {
        balances.report = {
          ...auto.report,
          updatedAt: now,
          updatedBy: 'Avtomatik (Tizim - 23:00)',
          isAutoGenerated: true,
          status: 'completed',
        }
      } else {
        balances.report = {
          matrix: {},
          outputs: {},
          balances: {},
          updatedAt: now,
          updatedBy: 'Tizim (23:00)',
          isUnfilled: true,
          status: 'unfilled',
        }
      }

      if (existingExpense) {
        await prisma.shopExpense.update({ where: { date }, data: { balances } })
      } else {
        await prisma.shopExpense.create({ data: { date, materials: {}, balances } })
      }
      finalSaved = balances.report
    }

    return NextResponse.json({
      date,
      saved: finalSaved,
      auto,
      prevEnd,
    })
  } catch (error: any) {
    console.error('Shop day report fetch error:', error)
    return NextResponse.json({ error: error.message }, { status: 500 })
  }
}

/**
 * Save the daily workshop report (Tab 3) for one date.
 * Body: { date: 'YYYY-MM-DD', report: { matrix, outputs, balances } }
 * Stored in ShopExpense.balances.report, so imported data in
 * materials / matrix / outputs is left untouched.
 */
export async function PUT(req: NextRequest) {
  try {
    const session = await getSession()
    if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
    if (session.role === 'SUPPLY') {
      return NextResponse.json({ error: "Supply roli shop-report ma'lumotlarini faqat ko'rishi mumkin" }, { status: 403 })
    }

    const body = await req.json()
    const date = body?.date
    if (!isDateStr(date)) {
      return NextResponse.json({ error: "Sana noto'g'ri" }, { status: 400 })
    }

    const report = sanitizeDayReport(body?.report)
    const now = new Date().toISOString()
    const existing = await prisma.shopExpense.findUnique({ where: { date } })
    const prevBalances = ((existing?.balances as any) || {}) as Record<string, any>

    const balances: Record<string, any> = { ...prevBalances }
    if (hasReportData(report)) {
      balances.report = {
        ...report,
        updatedAt: now,
        updatedBy: session.name,
        isAutoGenerated: false,
        isUnfilled: false,
        status: 'completed',
      }
    } else {
      // Everything cleared by the user -> mark as unfilled
      balances.report = {
        matrix: {},
        outputs: {},
        balances: {},
        updatedAt: now,
        updatedBy: session.name,
        isUnfilled: true,
        status: 'unfilled',
      }
    }

    if (existing) {
      await prisma.shopExpense.update({ where: { date }, data: { balances } })
    } else {
      await prisma.shopExpense.create({ data: { date, materials: {}, balances } })
    }

    return NextResponse.json({ success: true, date, updatedAt: now, updatedBy: session.name })
  } catch (error: any) {
    console.error('Shop day report save error:', error)
    return NextResponse.json({ error: error.message }, { status: 500 })
  }
}
