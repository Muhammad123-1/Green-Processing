import { NextRequest, NextResponse } from 'next/server'
import { prisma } from '@/lib/prisma'
import { getSession } from '@/app/actions/auth'
import { getDayReport, autoBuildDayReport } from '@/lib/shopReport'

export const dynamic = 'force-dynamic'

/**
 * Endpoint to auto-archive daily shop reports after 23:00 (kechki 11 dan keyin).
 * Gathers today's arrivals, material dispatches, and GP outputs.
 * Saves clean DayReport into ShopExpense.balances.report.
 * If no data was entered on that day, flags it as status: 'unfilled' ("To'ldirilmagan").
 */
export async function POST(req: NextRequest) {
  try {
    const session = await getSession()
    // Accessible by logged in users or cron triggers

    const nowUz = new Date(Date.now() + 5 * 3600 * 1000)
    const todayUz = nowUz.toISOString().slice(0, 10)
    const currentHourUz = nowUz.getUTCHours()

    // Find all dates from arrivals and expenses in the last 30 days
    const [arrivals, expenses] = await Promise.all([
      prisma.shopArrival.findMany({
        where: { date: { lte: todayUz } },
        orderBy: { date: 'desc' },
      }),
      prisma.shopExpense.findMany({
        where: { date: { lte: todayUz } },
        orderBy: { date: 'desc' },
      })
    ])

    const dateSet = new Set<string>()
    // Include today
    dateSet.add(todayUz)
    arrivals.forEach((a) => { if (a.date) dateSet.add(a.date) })
    expenses.forEach((e) => { if (e.date) dateSet.add(e.date) })

    const sortedDates = Array.from(dateSet).sort()
    let prevEndMap: Record<string, number> | null = null

    const processed: any[] = []

    for (const date of sortedDates) {
      // Only process past days OR today after 23:00
      const isPastOrAfter11PM = date < todayUz || (date === todayUz && currentHourUz >= 23)
      if (!isPastOrAfter11PM) continue

      const expense = expenses.find((e) => e.date === date)
      const existingReport = getDayReport(expense)

      // If user has already manually completed this report, respect their manual entry
      if (existingReport && !existingReport.isAutoGenerated && existingReport.status !== 'unfilled') {
        if (existingReport.balances?.end) {
          prevEndMap = existingReport.balances.end
        }
        continue
      }

      const dayArrivals = arrivals.filter((a) => a.date === date)
      const auto = autoBuildDayReport(date, dayArrivals, expense, prevEndMap)

      const now = new Date().toISOString()
      const prevBalances = ((expense?.balances as any) || {}) as Record<string, any>
      const balances: Record<string, any> = { ...prevBalances }

      if (auto.hasData) {
        balances.report = {
          ...auto.report,
          updatedAt: now,
          updatedBy: 'Avtomatik (Tizim - 23:00)',
          isAutoGenerated: true,
          status: 'completed',
        }
        if (auto.report.balances?.end) {
          prevEndMap = auto.report.balances.end
        }
      } else {
        balances.report = {
          matrix: {},
          outputs: {},
          balances: {},
          updatedAt: now,
          updatedBy: 'Tizim (23:00)',
          isUnfilled: true,
          status: 'unfilled',
        }
      }

      if (expense) {
        await prisma.shopExpense.update({
          where: { date },
          data: { balances },
        })
      } else {
        await prisma.shopExpense.create({
          data: {
            date,
            materials: {},
            balances,
          },
        })
      }

      processed.push({
        date,
        status: auto.hasData ? 'completed' : 'unfilled',
        totalArrivalKg: auto.totalArrivalKg,
        totalExpenseKg: auto.totalExpenseKg,
        totalOutputKg: auto.totalOutputKg,
      })
    }

    return NextResponse.json({
      success: true,
      todayUz,
      currentHourUz,
      processedCount: processed.length,
      details: processed,
    })
  } catch (error: any) {
    console.error('Auto archive error:', error)
    return NextResponse.json({ error: error.message }, { status: 500 })
  }
}

export async function GET(req: NextRequest) {
  return POST(req)
}
