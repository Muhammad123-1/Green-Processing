import { prisma } from '@/lib/prisma'
import { autoBuildDayReport, getDayReport } from '@/lib/shopReport'
import { syncInventoryBatchesFromDailyBalances } from '@/lib/fifoSync'

/**
 * Enterprise Workshop Report (Sex Hisoboti) Auto-Calculation & Archiving Engine.
 * 
 * Auto-calculates:
 * 1. Kirim (Raw material arrivals from ShopArrival)
 * 2. Chiqim (Production expenses and kitchen expenses from ShopExpense)
 * 3. GP (Finished goods output KFC)
 * 4. Ortib qolgan mahsulotlar / Qoldiq (Boshlang'ich qoldiq + Kirim - Chiqim = Yakuniy qoldiq)
 * 
 * "Unga hech kim ma'lumot kirgizmaydi, tizimni o'zi yozib boradi va arxivga saqlaydi."
 */
export async function autoSyncShopReportForDates(targetDates: string[]): Promise<number> {
  if (!targetDates || targetDates.length === 0) return 0

  const uniqueDates = Array.from(new Set(targetDates.filter((d) => Boolean(d && typeof d === 'string')))).sort()
  if (uniqueDates.length === 0) return 0

  let syncedCount = 0

  for (const date of uniqueDates) {
    try {
      const [expense, dayArrivals, earlierExpenses] = await Promise.all([
        prisma.shopExpense.findUnique({ where: { date } }),
        prisma.shopArrival.findMany({ where: { date }, orderBy: { id: 'asc' } }),
        prisma.shopExpense.findMany({
          where: { date: { lt: date } },
          orderBy: { date: 'desc' },
          take: 15,
        }),
      ])

      // Find closest earlier report with end balances
      let prevEnd: Record<string, number> | null = null
      for (const e of earlierExpenses) {
        const rep = getDayReport(e)
        const end = rep?.balances?.end
        if (end && Object.keys(end).length > 0) {
          prevEnd = end
          break
        }
      }

      const auto = autoBuildDayReport(date, dayArrivals, expense, prevEnd)
      const now = new Date().toISOString()
      const prevBalances = ((expense?.balances as any) || {}) as Record<string, any>
      const balances: Record<string, any> = { ...prevBalances }

      balances.report = {
        ...auto.report,
        updatedAt: now,
        updatedBy: 'Avtomatik (Tizim)',
        isAutoGenerated: true,
        status: auto.hasData ? 'completed' : 'unfilled',
      }

      if (expense) {
        await prisma.shopExpense.update({
          where: { date },
          data: { balances },
        })
      } else {
        await prisma.shopExpense.create({
          data: {
            date,
            materials: {},
            balances,
          },
        })
      }
      syncedCount++
    } catch (err) {
      console.error(`Error auto-syncing shop report for date ${date}:`, err)
    }
  }

  if (syncedCount > 0) {
    syncInventoryBatchesFromDailyBalances().catch((e) =>
      console.error('FIFO sync error after shop report auto-sync:', e)
    )
  }

  return syncedCount
}
